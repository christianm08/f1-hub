export interface MIconProps {
  /** Material Symbols snake_case name, e.g. "home", "sports_motorsports". */
  name: MIconName;
  /** Pixel size (width = height). Default 24. */
  size?: number;
  /** Use the filled (FILL=1) variant when available, else the outline one. Default false. */
  filled?: boolean;
  /** Optical weight. The svg-400 package bakes weight 400; 500-700 are emulated
      with a proportional stroke (paint-order: stroke fill). Values < 400 are ignored. */
  weight?: 100 | 200 | 300 | 400 | 500 | 600 | 700;
  className?: string;
  style?: CSSProperties;
  /** Accessible label. When omitted the icon is aria-hidden (decorative). */
  label?: string;
}

/**
 * Material Symbols icon rendered as inline SVG (no webfont, offline-safe).
 * Inherits text color via currentColor.
 *
 * @example <MIcon name="home" />
 * @example <MIcon name="favorite" filled size={20} label="Aggiungi ai preferiti" />
 */
export function MIcon({ name, size = 24, filled = false, weight = 400, className, style, label }: MIconProps) {
  const raw = (filled ? FILL[name] : undefined) ?? OUTLINE[name];
  let svg = raw;
  // weight emulation: stroke width in viewBox units (48-unit grid), scaled with size via CSS
  if (weight > 400) {
    const sw = ((weight - 400) / 100) * 1.5;
    svg = raw.replace("<svg", `<svg stroke="currentColor" stroke-width="${sw.toFixed(2)}"`);
  }
  return (
    <span
      className={["micon", weight > 400 ? "micon-bold" : "", className ?? ""].filter(Boolean).join(" ")}
      style={{ width: size, height: size, ...style }}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      // eslint-disable-next-line react/no-danger
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}

